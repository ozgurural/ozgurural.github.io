#!/usr/bin/env node
/*
 * A standalone Font Awesome stylesheet for a page outside the Jekyll build.
 *
 * enterprise-ai-architecture.html is a single self-contained file: it never
 * loads main.css, so it cannot reach the subsetted Font Awesome the rest of
 * the site compiles from _sass/vendor/font-awesome/. It was instead loading
 * cdnjs's full, unsubsetted all.min.css (18 KB, ~2000 icons for the 25 this
 * page actually draws) with no integrity hash, so a compromised or altered
 * CDN response would run unverified on the page.
 *
 * Both problems have the same fix already sitting in the repo.
 * subset-icon-fonts.py already scans this exact file (it's in
 * SCAN_ROOT_FILES) when it cuts assets/webfonts/fa-solid-900.woff2, so every
 * glyph this page draws already lives in that local, subsetted file. This
 * script just derives the minimal CSS that asks for them: the icon names are
 * read out of the page's own fa-<name> classes, resolved against Font
 * Awesome's own _variables.scss (the same table subset-icon-fonts.py reads),
 * and only the base display rules plus one @font-face and one content rule
 * per icon actually used are written out.
 *
 *   node scripts/vendor-page-icons.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PAGE = path.join(ROOT, 'enterprise-ai-architecture.html');
const VARS = path.join(ROOT, '_sass', 'vendor', 'font-awesome', '_variables.scss');
const OUT = path.join(ROOT, 'assets', 'css', 'enterprise-ai-architecture-icons.css');

const NOT_ICONS = new Set(['solid', 'regular', 'brands', 'fw', 'lg', 'xs', 'sm',
  'spin', 'pulse', 'border', 'pull-left', 'pull-right', 'stack', 'stack-1x',
  'stack-2x', 'inverse', 'li', 'ul', 'rotate-90', 'rotate-180', 'rotate-270',
  'flip-horizontal', 'flip-vertical', 'flip-both', 'beat', 'fade', 'shake',
  'bounce', 'spin-pulse', 'spin-reverse', 'layers', 'icon', 'font-path', 'var']);

const page = fs.readFileSync(PAGE, 'utf8');
const names = new Set();
for (const m of page.matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)) {
  const n = m[1];
  if (!NOT_ICONS.has(n) && !/^\d+x$/.test(n)) names.add(n);
}

const vars = fs.readFileSync(VARS, 'utf8');
const table = new Map();
for (const m of vars.matchAll(/^\$fa-var-([a-z0-9-]+):\s*\\([0-9a-fA-F]+);/gm)) {
  table.set(m[1], m[2].toUpperCase());
}

const resolved = [];   // {name, codepoint}
const unresolved = [];
for (const n of [...names].sort()) {
  if (table.has(n)) resolved.push({ name: n, cp: table.get(n) });
  else unresolved.push(n);
}

console.log(`${names.size} fa- token(s) found on the page`);
if (unresolved.length) {
  console.log(`  not in Font Awesome's table (brand icon, or a typo): ${unresolved.join(', ')}`);
}
console.log(`${resolved.length} icon(s) resolved`);

/* This page only ever writes fa-solid alongside its icon classes (no far/fab
 * in the class list, confirmed by unresolved staying empty for anything that
 * isn't a genuine solid glyph), so only the solid face is vendored. Extending
 * to brands/regular is the same shape if the page ever adds one: resolve
 * against the matching family's already-subsetted local file and add another
 * @font-face block below. */
const css = `/* Generated by scripts/vendor-page-icons.js. Do not edit by hand.
 *
 * The ${resolved.length} icons enterprise-ai-architecture.html actually draws,
 * pointed at the same subsetted local file the rest of the site already
 * ships (assets/webfonts/fa-solid-900.woff2 -- see subset-icon-fonts.py,
 * which scans this exact page). Replaces a CDN stylesheet that shipped
 * everything Font Awesome has for the 25 icons this page uses, with no
 * integrity hash on top of that.
 *
 * Re-run to update: node scripts/vendor-page-icons.js
 */

.fa-solid, .fas {
  font-family: 'Font Awesome 6 Free';
  font-weight: 900;
  -moz-osx-font-smoothing: grayscale;
  -webkit-font-smoothing: antialiased;
  display: var(--fa-display, inline-block);
  font-style: normal;
  font-variant: normal;
  line-height: 1;
  text-rendering: auto;
}

@font-face {
  font-family: 'Font Awesome 6 Free';
  font-style: normal;
  font-weight: 900;
  font-display: block;
  src: url("/assets/webfonts/fa-solid-900.woff2") format("woff2");
}

${resolved.map(({ name, cp }) => `.fa-${name}::before { content: "\\${cp}"; }`).join('\n')}
`;

fs.writeFileSync(OUT, css);
console.log(`-> ${path.relative(ROOT, OUT)}`);
